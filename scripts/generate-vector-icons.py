"""Regenerate the small used-icon vector set, not a font asset.

Uses the Flutter SDK's licensed Material icon outlines. The output stores only
paths used by this app; it needs no runtime parser or bundled font.
"""
import argparse
import os
import pathlib
import re

from fontTools.pens.qu2cuPen import Qu2CuPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.svgLib.path import parse_path
import xml.etree.ElementTree as ET

root = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--flutter-root', default=os.environ.get('FLUTTER_ROOT', r'E:\Programs\flutter'))
args = parser.parse_args()
sdk = pathlib.Path(args.flutter_root)
icons = (sdk / 'packages/flutter/lib/src/material/icons.dart').read_text(encoding='utf-8')
codes = {name: int(code, 16) for name, code in re.findall(r'static const IconData (\w+)\s*=\s*IconData\(\s*0x([\da-f]+),', icons)}
names = set()
for source in (root / 'client/lib').glob('*.dart'):
    if source.name == 'app_icon_paths.dart':
        continue
    names.update(re.findall(r'\bIcons\.(\w+)', source.read_text(encoding='utf-8')))
# These are framework defaults that the font-free wrappers provide explicitly.
names.update(['arrow_back', 'arrow_back_ios_new_rounded', 'close', 'menu', 'more_vert', 'arrow_drop_down', 'expand_more', 'chevron_left', 'chevron_right', 'share', 'drag_indicator', 'file_copy_outlined'])
font = TTFont(sdk / 'bin/cache/artifacts/material_fonts/materialicons-regular.otf')
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
scale = 24 / font['head'].unitsPerEm
output = ["// Generated by scripts/generate-vector-icons.py. Do not edit by hand.",
          "// Google Material icons (CC BY 4.0) and official Symbols Rounded overrides (Apache 2.0).",
          "// Sources and licenses: assets/licenses/material-icons.txt.",
          "import 'package:flutter/material.dart' show IconData, Icons;",
          "const appIconSymbols = <IconData>[" + ','.join('Icons.' + name for name in sorted(names)) + "];",
          "// Each list is a vector path: move=0, line=1, cubic=2, close=3.",
          "const appIconPaths = <int, List<double>>{"]
official = {'link_rounded': 'link', 'settings_outlined': 'settings'}
for name in sorted(names):
    code = codes[name]
    pen = RecordingPen()
    if name in official:
        # Official Symbols Rounded SVG uses a 960-unit, negative-Y viewport.
        # Normalize it once into exactly the same 24-unit canvas as old glyphs.
        source = root / 'client/assets/icons/material-symbols-rounded' / (official[name] + '_24px.svg')
        svg = ET.fromstring(source.read_text(encoding='utf-8'))
        assert svg.attrib['viewBox'] == '0 -960 960 960'
        converted = TransformPen(Qu2CuPen(pen, max_err=0.01, all_cubic=True), (1/40, 0, 0, 1/40, 0, 24))
        for path in svg.findall('{http://www.w3.org/2000/svg}path'):
            parse_path(path.attrib['d'], converted)
    else:
        converted = TransformPen(Qu2CuPen(pen, max_err=0.01, all_cubic=True), (scale, 0, 0, -scale, 0, 24))
        glyphs[cmap[code]].draw(converted)
    values = []
    for command, points in pen.value:
        if command in ['moveTo', 'lineTo', 'curveTo']:
            values.append({'moveTo': '0', 'lineTo': '1', 'curveTo': '2'}[command])
            values.extend(f'{coordinate:.4f}'.rstrip('0').rstrip('.') or '0' for point in points for coordinate in point)
        elif command == 'closePath':
            values.append('3')
        else:
            raise ValueError(command)
    output.append(f'  0x{code:x}: [{",".join(values)}], // {name}')
    if name == 'drag_indicator':
        # Reuse the same licensed glyph for the Android shelf's bulk drag grip.
        commands = []
        for command, points in pen.value:
            if command == 'closePath': commands.append('Z')
            else:
                commands.append({'moveTo':'M','lineTo':'L','curveTo':'C'}[command] +
                    ' '.join(f'{n:.4f}'.rstrip('0').rstrip('.') or '0' for point in points for n in point))
        native = root / 'client/android/app/src/main/res/drawable/ic_drag_all.xml'
        native.write_text('<!-- Generated Material icon; license: client/assets/licenses/material-icons.txt. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
            '<path android:fillColor="#FF000000" android:pathData="' + ' '.join(commands) + '"/>\n</vector>\n', encoding='utf-8')
output.append('};')
target = root / 'client/lib/app_icon_paths.dart'
target.write_text('\n'.join(output) + '\n', encoding='utf-8')
print(f'{len(names)} vector icons, {target.stat().st_size} bytes')
