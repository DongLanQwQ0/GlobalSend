import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=JSON.parse(await readFile(path.join(root,'packages/guides/usage.json'),'utf8'));
const platforms=['android','ipad','windows','web'];
if(source.schema!==1 || platforms.some(key=>!source.guides[key]))throw new Error('Missing platform guide');
for(const guide of Object.values(source.guides)){
  if(!guide.name || !guide.intro || !guide.sections.length || guide.sections.some(section=>!section.title || !section.steps.length || section.steps.some(step=>!step)))throw new Error('Incomplete guide');
}
const quote=value=>JSON.stringify(value).replace(/\$/g,'\\$');
const dart=`// Generated by scripts/generate-user-guides.mjs. Edit packages/guides/usage.json.\nclass GuideSection {\n  const GuideSection(this.title, this.steps);\n  final String title;\n  final List<String> steps;\n}\nclass PlatformGuide {\n  const PlatformGuide(this.name, this.intro, this.sections);\n  final String name, intro;\n  final List<GuideSection> sections;\n}\nconst userGuides = <String, PlatformGuide>{\n${platforms.map(key=>`  ${quote(key)}: PlatformGuide(${quote(source.guides[key].name)}, ${quote(source.guides[key].intro)}, [\n${source.guides[key].sections.map(section=>`    GuideSection(${quote(section.title)}, [${section.steps.map(quote).join(', ')}]),`).join('\n')}\n  ]),`).join('\n')}\n};\n`;
const ts=`// Generated by scripts/generate-user-guides.mjs. Edit packages/guides/usage.json.\nexport interface GuideSection {title:string;steps:string[]}\nexport interface PlatformGuide {name:string;intro:string;sections:GuideSection[]}\nexport const userGuides:Record<'android'|'ipad'|'windows'|'web',PlatformGuide>=${JSON.stringify(source.guides,null,2)};\n`;
const outputs=new Map([
  ['client/lib/user_guide_content.g.dart',dart],
  ['web/src/user_guide_content.ts',ts],
  ...platforms.map(key=>[`docs/guides/${key}.md`,`<!-- Generated by scripts/generate-user-guides.mjs. Edit packages/guides/usage.json. -->\n# GlobalSend ${source.guides[key].name} 使用指南\n\n${source.guides[key].intro}\n\n${source.guides[key].sections.map(section=>`## ${section.title}\n\n${section.steps.map((step,index)=>`${index+1}. ${step}`).join('\n')}`).join('\n\n')}\n`]),
]);
let stale=false;
for(const [file,contents] of outputs){
  const full=path.join(root,file), current=await readFile(full,'utf8').catch(()=>null);
  if(current===contents)continue;
  if(process.argv.includes('--check')){console.error(`Guide content is stale: ${file}`);stale=true;continue;}
  await mkdir(path.dirname(full),{recursive:true});await writeFile(full,contents);
}
if(stale)process.exitCode=1;
else console.log(`${outputs.size} guide outputs ${process.argv.includes('--check')?'match':'generated'}.`);
